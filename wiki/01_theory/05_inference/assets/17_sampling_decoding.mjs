const tokens = ["A", "B", "C", "D", "EOS"];
const logits = [2, 1, 0, -1, -2];

function softmax(xs) {
  const m = Math.max(...xs.filter(Number.isFinite));
  const es = xs.map((x) => (Number.isFinite(x) ? Math.exp(x - m) : 0));
  const z = es.reduce((a, b) => a + b, 0);
  return es.map((x) => x / z);
}

function fmt(xs) {
  return xs.map((x) => x.toFixed(3)).join("  ");
}

const p = softmax(logits);
const ranked = logits.map((_, i) => i).sort((a, b) => logits[b] - logits[a] || a - b);
const topK = ranked.slice(0, 3);
const topP = [];
let mass = 0;
for (const i of ranked) {
  topP.push(i);
  mass += p[i];
  if (mass >= 0.8) break;
}
const masked = (kept) => softmax(logits.map((value, i) => kept.includes(i) ? value : -Infinity));
const pK3 = masked(topK);
const pP08 = masked(topP);
const pTemp05 = softmax(logits.map((x) => x / 0.5));
const sign = (number, digits = 3) => number.toFixed(digits).replace("-", "−");
const logitText = logits.map((x) => String(x).replace("-", "−")).join(", ");
const candidates = (ids) => ids.map((i) => tokens[i]).join("、");
const greedy = ranked[0];
if (tokens[ranked[0]] !== "A" || tokens[ranked[1]] !== "B") {
  throw new Error("Update the teaching beam conditional table for this new first-step ranking.");
}
const conditional = [
  ["A", "A", 0.40], ["A", "B", 0.35], ["A", "EOS", 0.25],
  ["B", "A", 0.60], ["B", "EOS", 0.30], ["B", "B", 0.10],
];
const beam = conditional.map(([prefix, next, probability]) => ({
  label: next === "EOS" ? `${prefix} EOS` : prefix + next,
  score: Math.log(p[tokens.indexOf(prefix)]) + Math.log(probability),
})).sort((a, b) => b.score - a.score);
const beamLine = (item) => `${item.label} ${sign(item.score)}`;
const eosRank = beam.findIndex((item) => item.label === "A EOS") + 1;
const page = readFileSync(new URL("../17_sampling_decoding_analysis.md", import.meta.url), "utf8");
if (!page.includes(`\`(${logits.join(", ")})\``) ||
    !page.includes(p[greedy].toFixed(6)) ||
    !page.includes(`A EOS`) ||
    !page.includes(`合并排名第 ${eosRank}`)) {
  throw new Error("Teaching page and generated decoding example disagree.");
}

